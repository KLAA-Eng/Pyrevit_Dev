"""Generate the KLCode GUI icon and logo resources from their SVG sources.

Writes one deterministic file, ``lib/GUI/Resources/klIcons.xaml``: a leaf
resource dictionary that defines no brushes. It holds

* one ``klicon<Role>`` GeometryGroup per role in ``ROLES``, drawn by the
  foundation's ``KlaGuiIcon`` presenter; and
* the KLCode logo from ``lib/_logos/klcLogo.svg``, as one self-contained
  ``klcLogo`` DataTemplate: the slash and letter outlines with the SVG group's
  scale and offset, on a canvas the size of the view box. The template's
  Viewbox is unsized, so the window header sets the logo size, and its fills
  reference the palette's ``klcBorderColor`` and ``klcTextColor``.

Usage::

    python -B scripts/generate_gui_icons.py           # rewrite the file
    python -B scripts/generate_gui_icons.py --check   # fail if it is stale

This is a CPython 3.9+ development script (it uses ``ElementTree.indent``).
The generated XAML needs no SVG renderer or Python dependency at run time,
and the source SVGs stay in the repository.
"""
from pathlib import Path
import argparse
import re
import xml.etree.ElementTree as ET


# Paths and XML namespaces
# ------------------------------------------------------------------
ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'lib' / '_icons' / 'gui'  # Approved icon SVGs and source.json.
LOGO_SVG = ROOT / 'lib' / '_logos' / 'klcLogo.svg'
ICONS_XAML = ROOT / 'lib' / 'GUI' / 'Resources' / 'klIcons.xaml'
WPF = 'http://schemas.microsoft.com/winfx/2006/xaml/presentation'
XAML = 'http://schemas.microsoft.com/winfx/2006/xaml'
SVG = 'http://www.w3.org/2000/svg'
GENERATED_COMMENT = (
    '<!-- Generated by scripts/generate_gui_icons.py: GUI icon geometry (klicon<Role>) and the '
    'KLCode logo template (klcLogo) from klcLogo.svg. Edit the SVG sources and manifest, not this file. -->')


# Icon roles
# ------------------------------------------------------------------
# Each role becomes the klicon<Role> key; its value names the SVG file in
# lib/_icons/gui/svg. The groups and the Future prefix record which windows use
# a role, as the icon README's status column does.
ROLES = {
    # Shared dialogs: Selection (Search, Group), Message and Action Choice severity icons,
    # and the shared Details toggle. InfoAlert and WarnAlert also serve CustomAlert and the compiled alert.
    'Search': 'search', 'Group': 'layers-2',
    'InfoAlert': 'info', 'WarnAlert': 'triangle-alert',
    # ErrorAlert also serves the compiled alert and Startup Importer blocking issues (circle-x retired 2026-10-31);
    # SuccessAlert also draws the recall window's current-selection action (FutureCurrentSelection merged 2026-10-31).
    'ErrorAlert': 'octagon-alert', 'SuccessAlert': 'check-check',
    'ChevRight': 'chevron-right', 'ChevDown': 'chevron-down',
    # Other live windows: compiled Family Studio (List, Grid, Fav).
    'List': 'list', 'Grid': 'layout-grid', 'Fav': 'star',
    # Future: used only by the Match recall window in lib/GUI/_future/match, which no tool opens.
    'FutureFilterList': 'list-filter', 'FutureRegex': 'regex', 'FutureClearSearch': 'x',
    'FutureTags': 'tags', 'FutureRead': 'eye', 'FutureFilterFunnel': 'funnel',
    'FuturePointer': 'mouse-pointer-2', 'FutureRectSelect': 'scan',
}


# Logo
# ------------------------------------------------------------------
# How far, in view-box units, the logo outlines may extend past the view box.
# This is headroom for rounding in Inkscape's group transform (the current SVG
# overshoots by far less than one unit); more means the SVG and its view box
# disagree.
LOGO_TOLERANCE = 2.0

# The palette brush for each logo outline, in the order the SVG lists its two
# paths: the slash, then the letters. The fills use DynamicResource because
# klIcons.xaml does not merge the palette; they resolve from the window that
# draws the logo, which always has the palette loaded.
LOGO_FILLS = ('klcBorderColor', 'klcTextColor')


# XML helpers
# ------------------------------------------------------------------
def element(parent, name, attributes=None):
    """Append a WPF-namespace child element.

    Args:
        parent: ElementTree element that receives the child.
        name: Local WPF element name, such as ``'PathGeometry'``.
        attributes: Optional mapping of attribute names to string values.

    Returns:
        The new child element.
    """
    return ET.SubElement(parent, '{' + WPF + '}' + name, attributes or {})


def _register_namespaces():
    """Map the WPF and ``x:`` namespaces to the prefixes XAML uses.

    ElementTree keeps one global prefix registry, so this runs before each
    serialisation instead of once at import.
    """
    ET.register_namespace('', WPF)
    ET.register_namespace('x', XAML)


def _serialise(root, comment):
    """Return a resource dictionary as indented XAML text.

    Args:
        root: The ResourceDictionary element to serialise.
        comment: XML comment written as the file's first line.

    Returns:
        The comment, the four-space indented XAML and a final newline.
    """
    ET.indent(root, space='    ')
    return comment + '\n' + ET.tostring(root, encoding='unicode') + '\n'


def _numbers(text):
    """Return the numbers in an SVG number list, such as a view box.

    Args:
        text: Numbers separated by commas, whitespace or both.

    Returns:
        The numbers as floats, in order.
    """
    return [float(value) for value in re.split(r'[\s,]+', text.strip())]


# Icon geometry
# ------------------------------------------------------------------
def geometry(svg):
    """Translate one Lucide SVG primitive into a WPF geometry element.

    The translation keeps the primitive's coordinates, so every icon keeps its
    full 24-unit canvas and apparent size.

    Args:
        svg: SVG ``path``, ``circle``, ``rect``, ``line`` or ``polyline``
            element from an icon file.

    Returns:
        A tuple ``(name, attributes)``: the WPF geometry element name and its
        attribute mapping.

    Raises:
        ValueError: The primitive has a transform or is not a supported shape.
    """
    name = svg.tag.rsplit('}', 1)[-1]
    attrs = svg.attrib
    if 'transform' in attrs:
        raise ValueError('Transforms require an explicit converter implementation.')
    if name == 'path':
        return 'PathGeometry', {'Figures': attrs['d']}
    if name == 'circle':
        return 'EllipseGeometry', {'Center': attrs['cx'] + ',' + attrs['cy'],
                                   'RadiusX': attrs['r'], 'RadiusY': attrs['r']}
    if name == 'rect':
        corner_x = attrs.get('rx', '0')
        return 'RectangleGeometry', {'Rect': ','.join(attrs[key] for key in ('x', 'y', 'width', 'height')),
                                     'RadiusX': corner_x, 'RadiusY': attrs.get('ry', corner_x)}
    if name == 'line':
        return 'LineGeometry', {'StartPoint': attrs['x1'] + ',' + attrs['y1'],
                                'EndPoint': attrs['x2'] + ',' + attrs['y2']}
    if name == 'polyline':
        return 'PathGeometry', {'Figures': 'M' + attrs['points']}
    raise ValueError('Unsupported SVG primitive: ' + name)


def role_parts():
    """Read every role's SVG and translate its primitives.

    A few Lucide parts are marked ``fill="currentColor"``, such as the dot in
    ``tags.svg``. ``KlaGuiIcon`` only strokes geometry, so those parts draw as
    small outlines rather than filled shapes.

    Returns:
        A list of ``(role, parts)`` tuples sorted by role name, where ``parts``
        is a list of ``(name, attributes)`` tuples from ``geometry()``.

    Raises:
        ValueError: An icon does not use the 24-unit Lucide canvas, or one of
            its primitives cannot be translated.
    """
    result = []
    for role, source in sorted(ROLES.items()):
        svg = ET.parse(ASSETS / 'svg' / (source + '.svg')).getroot()
        if svg.attrib.get('viewBox') != '0 0 24 24':
            raise ValueError('Unexpected icon view box: ' + source)
        result.append((role, [geometry(child) for child in svg]))
    return result


def generate_icons():
    """Build the complete text of ``klIcons.xaml``.

    Returns:
        The generated XAML, byte for byte what the file must contain.

    Raises:
        ValueError: An icon or the logo SVG fails validation.
    """
    _register_namespaces()
    root = ET.Element('{' + WPF + '}ResourceDictionary')
    # Write one GeometryGroup per role. Sorting by role name keeps the output
    # stable however ROLES is ordered.
    for role, parts in role_parts():
        group = element(root, 'GeometryGroup', {'{' + XAML + '}Key': 'klicon' + role})
        for name, attrs in parts:
            element(group, name, attrs)
    _append_logo(root)
    return _serialise(root, GENERATED_COMMENT)


# SVG path data
# ------------------------------------------------------------------
# One SVG number: an optional sign, digits with an optional decimal point (or a
# leading point), and an optional exponent. A second point starts a new number,
# as SVG's compact form allows ("1.5.5" is 1.5 and .5).
_NUM = re.compile(r'[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')
_PATH_TOKEN = re.compile(r'[MLHVCSQTAZmlhvcsqtaz]|' + _NUM.pattern)
_COMMAND_ARGS = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6, 'S': 4, 'Q': 4, 'T': 2, 'A': 7, 'Z': 0}


def path_points(d):
    """Return every absolute point an SVG path names.

    Collects end points and curve control points. That is enough to check that
    a path stays inside a box; it is not the curve's exact bounds.

    Args:
        d: SVG path data, absolute or relative commands.

    Returns:
        A list of ``(x, y)`` float tuples in path order.

    Raises:
        ValueError: The data does not start with a command, numbers follow
            a close-path command, or a command has too few numbers.
    """
    tokens = _PATH_TOKEN.findall(d)
    points = []
    x = y = 0.0
    start = (0.0, 0.0)
    command = None
    i = 0
    while i < len(tokens):
        if tokens[i].isalpha():
            command = tokens[i]
            i += 1
            if command.upper() == 'Z':
                # Close path: the pen returns to the subpath start without
                # naming a new point.
                x, y = start
                continue
        # A number without a new command repeats the previous one, as SVG
        # allows for every command except close path.
        if command is None or command.upper() == 'Z':
            raise ValueError('Path data has numbers without a command: ' + d[:40])
        relative, kind = command.islower(), command.upper()
        count = _COMMAND_ARGS[kind]
        args = [float(token) for token in tokens[i:i + count]]
        if len(args) < count or any(token.isalpha() for token in tokens[i:i + count]):
            raise ValueError('Path command %s needs %d numbers: %s' % (command, count, d[:40]))
        i += count
        if kind == 'H':
            x = x + args[0] if relative else args[0]
        elif kind == 'V':
            y = y + args[0] if relative else args[0]
        elif kind == 'A':
            # Only the arc's end point is a position; its radii and flags are not.
            x, y = (x + args[5], y + args[6]) if relative else (args[5], args[6])
        else:
            # M, L, C, S, Q and T: every coordinate pair is a point, and in a
            # relative command each pair is measured from the current point.
            for px, py in zip(args[0::2], args[1::2]):
                points.append((x + px, y + py) if relative else (px, py))
            x, y = points[-1]
            if kind == 'M':
                start = (x, y)
                # Further pairs after a moveto are linetos.
                command = 'l' if relative else 'L'
            continue
        points.append((x, y))
    return points


# Logo
# ------------------------------------------------------------------
def _matrix(transform):
    """Parse an axis-aligned SVG transform.

    Args:
        transform: ``matrix(a,0,0,d,e,f)``, ``translate(e[,f])``,
            ``scale(a[,d])`` or an empty string.

    Returns:
        A tuple ``(a, d, e, f)``: the x and y scale, then the x and y offset.

    Raises:
        ValueError: The transform rotates, skews, mirrors or is not one of
            the supported forms.
    """
    if not transform:
        return (1.0, 1.0, 0.0, 0.0)
    m = re.match(r'^\s*matrix\(([^)]*)\)\s*$', transform)
    if m:
        a, b, c, d, e, f = _numbers(m.group(1))
        if abs(b) > 1e-9 or abs(c) > 1e-9 or a <= 0 or d <= 0:
            raise ValueError('The logo group transform must be a positive scale and offset only: ' + transform)
        return (a, d, e, f)
    m = re.match(r'^\s*translate\(([^)]*)\)\s*$', transform)
    if m:
        values = _numbers(m.group(1))
        return (1.0, 1.0, values[0], values[1] if len(values) > 1 else 0.0)
    m = re.match(r'^\s*scale\(([^)]*)\)\s*$', transform)
    if m:
        values = _numbers(m.group(1))
        scale_x, scale_y = values[0], values[1] if len(values) > 1 else values[0]
        if scale_x <= 0 or scale_y <= 0:
            raise ValueError('The logo group transform must be a positive scale and offset only: ' + transform)
        return (scale_x, scale_y, 0.0, 0.0)
    raise ValueError('Unsupported logo transform: ' + transform)


def _append_logo(root):
    """Append the ``klcLogo`` DataTemplate that draws the KLCode logo.

    The template is self-contained: each outline's path data, the SVG's
    combined transform and the view-box size are written inline, so the logo
    is a single resource. The outlines keep their SVG coordinates and the
    transform places them, so the drawing matches the source file. The
    Viewbox has no size of its own: it fills the slot its host gives it, which
    in the window header is ``klcLogoWidth`` by ``klcLogoHeight``. Change those
    two tokens to resize the logo everywhere.

    Args:
        root: The ResourceDictionary element to extend.

    Raises:
        ValueError: The logo SVG does not have exactly two outlines, its view
            box does not start at 0,0, its paths use different or unsupported
            transforms, or the outlines leave the view box.
    """
    svg = ET.parse(LOGO_SVG).getroot()
    view_box = _numbers(svg.attrib['viewBox'])
    if view_box[0] or view_box[1]:
        raise ValueError('The logo view box must start at 0,0.')
    width, height = view_box[2], view_box[3]
    paths = list(svg.iter('{' + SVG + '}path'))
    if len(paths) != len(LOGO_FILLS):
        raise ValueError('The logo SVG must hold exactly two paths (slash, letters); found %d' % len(paths))

    # Combine each path's own transform with every enclosing group's, innermost
    # first. Inkscape scales the outlines with a group transform rather than
    # rewriting their coordinates.
    parents = {child: parent for parent in svg.iter() for child in parent}
    transforms = []
    for path in paths:
        a, d, e, f, node = 1.0, 1.0, 0.0, 0.0, path
        while node is not None and node is not svg:
            ga, gd, ge, gf = _matrix(node.attrib.get('transform', ''))
            a, d, e, f = ga * a, gd * d, ga * e + ge, gd * f + gf
            node = parents.get(node)
        transforms.append((a, d, e, f))
    if len(set(transforms)) != 1:
        raise ValueError('Both logo paths must share one transform.')
    a, d, e, f = transforms[0]

    # Validate that both transformed outlines stay inside the view box, so the
    # canvas below clips nothing.
    for path in paths:
        points = path_points(path.attrib['d'])
        xs = [a * px + e for px, _ in points]
        ys = [d * py + f for _, py in points]
        if (min(xs) < -LOGO_TOLERANCE or max(xs) > width + LOGO_TOLERANCE
                or min(ys) < -LOGO_TOLERANCE or max(ys) > height + LOGO_TOLERANCE):
            raise ValueError('Logo geometry leaves the view box: x %.2f..%.2f y %.2f..%.2f'
                             % (min(xs), max(xs), min(ys), max(ys)))

    # Write the template. WPF reads a six-number RenderTransform as a matrix
    # (M11, M12, M21, M22, OffsetX, OffsetY); ten significant digits keep
    # Inkscape's transform unrounded. Each Path needs its own copy: a transform
    # on the Canvas would also move the Canvas clip.
    matrix = ','.join('%.10g' % value for value in (a, 0, 0, d, e, f))
    template = element(root, 'DataTemplate', {'{' + XAML + '}Key': 'klcLogo'})
    box = element(template, 'Viewbox', {'SnapsToDevicePixels': 'True', 'Stretch': 'Uniform'})
    canvas = element(box, 'Canvas', {'Width': '%g' % width, 'Height': '%g' % height, 'ClipToBounds': 'True'})
    for path, brush in zip(paths, LOGO_FILLS):
        element(canvas, 'Path', {'Data': path.attrib['d'], 'Fill': '{DynamicResource %s}' % brush,
                                 'RenderTransform': matrix})


# Command line
# ------------------------------------------------------------------
def main():
    """Rewrite ``klIcons.xaml``, or with ``--check`` fail when it is stale.

    Without ``--check``, writes the file even when it is already current.

    Raises:
        SystemExit: ``--check`` found the file missing or different from the
            generated text.
    """
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='Fail if resources need regeneration.')
    args = parser.parse_args()
    text = generate_icons()
    # Compare as text, so a Windows checkout with CRLF line endings still counts
    # as current.
    stale = not ICONS_XAML.exists() or ICONS_XAML.read_text(encoding='utf-8') != text
    if args.check:
        if stale:
            raise SystemExit('GUI artwork resources are stale (%s); run scripts/generate_gui_icons.py.'
                             % ICONS_XAML.relative_to(ROOT))
    else:
        # Write LF line endings on every platform. Text mode would write CRLF on
        # Windows, and Git may then show the whole file as changed (the
        # repository has no .gitattributes to normalise it).
        with open(ICONS_XAML, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(text)
    print('{} approved GUI icon roles and the KLCode logo verified.'.format(len(ROLES)))


if __name__ == '__main__':
    main()
